/**
 * 示意底图（演示用，非图商数据）
 *
 * 画法学地图 App 的通用矢量底图：浅灰陆地、蓝色水系、绿色的保护地、城镇浅灰色块、高速与普通道路。
 * 要素位置取自公开地理常识的近似经纬度，用与 trip.ts 相同的投影（project）落到 SVG 坐标，路线叠上去严丝合缝。
 * 样式只用通用的地图配色（globals.css 的 --ui-map-*），不按某条线路的地貌着色；也不画行政区界线。
 * 要素范围比路线视框（MAP_VIEW）大一圈，视框以外的部分用来铺满地图容器的空白处。
 */

import { project, smoothPath } from './trip';

type LL = readonly [number, number];

const pts = (list: readonly LL[]) => list.map(([lon, lat]) => project(lon, lat));
const line = (list: readonly LL[], tension = 0.5) => smoothPath(pts(list), tension);
const area = (list: readonly LL[], tension = 0.5) => `${smoothPath(pts([...list, list[0]]), tension)} Z`;

/** 公里 → SVG 单位（这一纬度带上经纬两个方向都约 0.9） */
const KM = 0.9;

export interface Blob {
  cx: number;
  cy: number;
  rx: number;
  ry: number;
}

const blob = (lon: number, lat: number, rxKm: number, ryKm: number): Blob => {
  const [cx, cy] = project(lon, lat);
  return { cx, cy, rx: rxKm * KM, ry: ryKm * KM };
};

